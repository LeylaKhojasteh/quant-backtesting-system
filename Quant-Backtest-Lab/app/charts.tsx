/** Permanent, compact event guide for the price chart panel. */
export function PriceChartLegend({ overlay }: { overlay?: string }) {
  const show = (key: string) => {
    const o = overlay ?? 'Signals + Trades';
    if (key === 'bull' || key === 'bear') return true;
    if (key === 'entry' || key === 'tp' || key === 'sl' || key === 'eod') return o.includes('Trades') || o === 'Signals + Trades';
    return o.includes('Signals');
  };
  return (
    <TooltipProvider delayDuration={150}>
      <div className="chart-legend">
        <span className="chart-legend-title">EVENT GUIDE</span>
      {PRICE_CHART_LEGEND.filter((item) => show(item.key)).map((item) => (
        <Tooltip key={item.key}>
          <TooltipTrigger asChild>
            <button type="button" className="chart-legend-item" aria-label={`About ${item.label}`}>
              {item.key === 'bull' || item.key === 'bear' ? (
                <i className="legend-body" style={{ background: item.color }} />
              ) : (
                <i className="legend-tag" style={{ borderColor: item.color, color: item.color }}>{item.code}</i>
              )}
              <span>{item.label}</span>
            </button>
          </TooltipTrigger>
          <TooltipContent className="max-w-80">
            <strong>{item.label}</strong>
            <p style={{ marginTop: 4 }}>{item.description}</p>
            <p className="meta" style={{ marginTop: 4 }}>{item.meaning}</p>
          </TooltipContent>
        </Tooltip>
      ))}
      </div>
    </TooltipProvider>
  );
}

export function CandleChart({
  context,
  trade,
  overlay = 'Signals + Trades',
  onSelect,
}: {
  context?: boolean;
  trade?: Trade;
  overlay?: string;
  onSelect?: (i: number) => void;
}) {
  const [zoom, setZoom] = useState(1);
  const [pan, setPan] = useState(0);
  const [hover, setHover] = useState<number | null>(null);
  const drag = useRef<number | null>(null);
  const { ref, width, height, ready } = useElementSize();

  // A wheel over the plot belongs to the chart: zoom it and stop the event so the
  // page does not scroll at the same time. Native listeners are required because
  // React's synthetic wheel handler is passive, so preventDefault is ignored.
  const hostRef = useRef<HTMLDivElement | null>(null);
  useEffect(() => {
    const node = hostRef.current;
    if (!node) return;
    const onWheel = (e: WheelEvent) => {
      e.preventDefault();
      e.stopPropagation();
      setZoom((v) => Math.max(1, Math.min(5, v + (e.deltaY < 0 ? 0.25 : -0.25))));
    };
    node.addEventListener('wheel', onWheel, { passive: false });
    return () => node.removeEventListener('wheel', onWheel);
  }, []);

  const base: Candle[] = context && trade
    ? Array.from({ length: 18 }, (_, i) => {
        const t = trade.signal + (i - 3) * M15_MS;
        const ratio = Math.max(0, Math.min(1, (t - trade.entryTime) / (trade.exitTime - trade.entryTime)));
        const mid =
          trade.entry +
          (trade.exit - trade.entry) * ratio +
          (t < trade.entryTime ? Math.sin(i) * 0.7 : Math.sin(i * 1.3) * 0.3);
        const o = mid + 0.35 * Math.sin(i * 2);
        const c = mid + 0.3 * Math.cos(i * 2);
        return { t, o, c, h: Math.max(o, c) + 0.3, l: Math.min(o, c) - 0.3 };
      })
    : candles;

  const count = Math.max(6, Math.round(base.length / zoom));
  const start = clamp(pan, 0, Math.max(0, base.length - count));
  const data = base.slice(start, start + count);

  const levels =
    trade && context
      ? [trade.entry, trade.sl, trade.tp]
      : overlay.includes('Trades')
        ? trades.flatMap((t) => [t.entry, t.exit])
        : [];

  const lo = Math.min(...data.map((c) => c.l), ...levels) - 2;
  const hi = Math.max(...data.map((c) => c.h), ...levels) + 2;

  // Markers live in dedicated gutters above and below the candle region, so a
  // label can never sit on top of a candle body or wick.
  const pad = { l: 52, r: 64, t: 26, b: 34 };
  const plotW = Math.max(40, width - pad.l - pad.r);
  const plotH = Math.max(40, height - pad.t - pad.b);
  const slot = plotW / Math.max(1, data.length);
  const x = (i: number) => pad.l + (i + 0.5) * slot;
  const y = (v: number) => pad.t + ((hi - v) / (hi - lo || 1)) * plotH;

  const LABEL_H = 11;
  /** Longest vertical connector the leader may draw toward its candle. */
  const LEADER_MAX = 14;
  /** Shortest connector; a stub shorter than this reads as a stray mark. */
  const LEADER_MIN = 6;
  /** Drawn connector length; fixed so the candle gap stays exact. */
  const LEADER_LEN = clamp(10, LEADER_MIN, LEADER_MAX);
  /** Empty space kept between the connector tip and the candle body / wick. */
  const CONNECTOR_GAP = 8;
  /** Row separation used when two events share a candle column. */
  const LANE_STEP = LABEL_H + 3;

  const labelEvery = Math.max(1, Math.floor(data.length / 6));

  // Candles are obstacles first: a marker must never cover a body or wick, so a
  // label keeps its short distance to its own candle and slides sideways when a
  // neighbour is in the way. Staying close preserves the event-to-candle link.
  const placed: { x1: number; x2: number; y1: number; y2: number }[] = data.map((c, i) => {
    const half = Math.max(1.4, slot * 0.6) / 2 + 4;
    return { x1: x(i) - half, x2: x(i) + half, y1: y(c.h) - 4, y2: y(c.l) + 4 };
  });

  const marker = (
    owner: Trade,
    timestamp: number,
    label: string,
    color: string,
    below: boolean,
    kind: 'Signal' | 'Entry' | 'Exit',
    reason?: Trade['reason'],
  ) => {
    const i = candleIndexAt(data, timestamp);
    if (i === null) return null;

    const candle = data[i];
    const cx = x(i);
    const boxW = label.length * 5.4 + 9;

    // Placement rules:
    // 1. the tag is centred on its own candle column and never drifts sideways
    // 2. it sits on the side of the candle with room: above when the candle is
    //    low in the plot, below when it is high
    // 3. collisions resolve into stacked lanes on that same vertical axis
    const edgeFor = (isAbove: boolean) => (isAbove ? y(candle.h) : y(candle.l));
    const roomFor = (isAbove: boolean) =>
      isAbove ? edgeFor(true) - pad.t : pad.t + plotH - edgeFor(false);
    const need = CONNECTOR_GAP + LEADER_LEN + LABEL_H;
    let above = roomFor(false) < need && roomFor(true) >= need;
    if (roomFor(above) < need) above = roomFor(true) >= roomFor(false);

    const minCy = pad.t + LABEL_H / 2;
    const maxCy = pad.t + plotH - LABEL_H / 2;
    const colL = cx - boxW / 2 - 2;
    const colR = cx + boxW / 2 + 2;
    const freeRow = (ly: number) =>
      !placed.some((r) => colL < r.x2 && colR > r.x1 && ly - LABEL_H / 2 < r.y2 && ly + LABEL_H / 2 > r.y1);
    const fitsRow = (ly: number) => ly >= minCy && ly <= maxCy && freeRow(ly);

    // Candidate rows on one side, ordered so the shortest connector wins. Only
    // rows further from the candle are valid: moving toward it would shorten the
    // connector below LEADER_MIN and push the tag onto the price action.
    const sideRows = (isAbove: boolean) => {
      const edge = edgeFor(isAbove);
      const base = isAbove
        ? edge - CONNECTOR_GAP - LEADER_LEN - LABEL_H / 2
        : edge + CONNECTOR_GAP + LEADER_LEN + LABEL_H / 2;
      const step = isAbove ? -LANE_STEP : LANE_STEP;
      return [0, 1, 2].map((k) => base + step * k);
    };

    const preferred = sideRows(above);
    const other = sideRows(!above);
    const pick = preferred.find(fitsRow) ?? other.find(fitsRow);
    let useAbove = above;
    let cy: number;
    if (pick !== undefined) {
      useAbove = preferred.includes(pick) ? above : !above;
      cy = pick;
    } else {
      // Both sides are blocked: keep the preferred row, clamped into the plot.
      useAbove = above;
      cy = clamp(preferred[0], minCy, maxCy);
    }
    above = useAbove;
    const anchorEdge = edgeFor(above);

    placed.push({
      x1: colL,
      x2: colR,
      y1: cy - LABEL_H / 2,
      y2: cy + LABEL_H / 2,
    });

    const price = kind === 'Entry' ? owner.entry : kind === 'Signal' ? candle.c : owner.exit;

    // Event type is explicit so a marker can be read without the legend:
    // Signal -> Entry -> Exit, with the exit reason spelled out.
    const eventName =
      kind === 'Signal'
        ? owner.direction === 'LONG' ? 'LONG SIGNAL' : 'SHORT SIGNAL'
        : kind === 'Entry'
          ? 'ENTRY'
          : reason === 'TP' ? 'TAKE PROFIT EXIT'
            : reason === 'SL' ? 'STOP LOSS EXIT'
              : 'END OF DATA EXIT';
    const eventNote =
      kind === 'Signal'
        ? 'Strategy condition satisfied on this candle. Not yet an executed trade.'
        : kind === 'Entry'
          ? 'Executed entry price and time.'
          : reason === 'TP' ? 'Closed because the take profit target was reached.'
            : reason === 'SL' ? 'Closed because the stop loss level was reached.'
              : 'Closed because backtest data ended while the position was open.';
    const title =
      `${eventName}\nTrade #${owner.id}\n${owner.direction}\n` +
      `${price === undefined ? 'Price n/a' : fmt(price)}\n${time(timestamp, true)}\n\n${eventNote}` +
      (kind === 'Signal' ? '' : `\nExit reason: ${owner.reason}`);

    // Face of the tag nearest the candle: bottom edge when the tag sits above.
    const gapFrom = above ? cy + LABEL_H / 2 : cy - LABEL_H / 2;
    // Strict direction: a tag above its candle draws downward, a tag below draws
    // upward. The tip always stops CONNECTOR_GAP short of the wick, so the line
    // points at the candle without ever touching it.
    const runY = above ? anchorEdge - CONNECTOR_GAP : anchorEdge + CONNECTOR_GAP;
    const runLen = Math.abs(runY - gapFrom);
    const drawLen = runLen >= LEADER_MIN ? runLen : 0;

    return (
      <g
        key={`${owner.id}-${label}`}
        className="candle-marker"
        data-candle-x={cx}
        data-candle-edge={anchorEdge}
        tabIndex={0}
        role="button"
        aria-label={`${label} trade ${owner.id}`}
        onClick={() => onSelect?.(owner.id - 1)}
        onKeyDown={(e) => e.key === 'Enter' && onSelect?.(owner.id - 1)}
      >
        {/* vertical connector: always on the candle axis, tip short of the wick */}
        {drawLen > 0 && (
          <line
            x1={cx}
            y1={gapFrom}
            x2={cx}
            y2={above ? gapFrom + drawLen : gapFrom - drawLen}
            stroke={color}
            strokeWidth="1"
            strokeLinecap="round"
            opacity=".75"
          />
        )}
        <rect
          x={cx - boxW / 2}
          y={cy - LABEL_H / 2}
          width={boxW}
          height={LABEL_H}
          rx="3.5"
          fill="var(--surface-elevated)"
          stroke={color}
          strokeWidth=".8"
        />
        <text x={cx} y={cy + 3.4} textAnchor="middle" style={{ fill: color, fontSize: 10 }}>
          {label}
        </text>
        <title>{title}</title>
      </g>
    );
  };

  const overlays = (context && trade ? [trade] : trades).flatMap((t) => {
    const showSignals = context || overlay.includes('Signals');
    const showTrades = context || overlay.includes('Trades');
    const entryIdx = candleIndexAt(data, t.entryTime);
    const nodes: React.ReactNode[] = [];

    if (showSignals) {
      nodes.push(
        marker(t, t.signal, `${t.direction === 'LONG' ? 'L' : 'S'}${t.id}`, t.direction === 'LONG' ? green : red, false, 'Signal'),
      );
    }
    if (showTrades && entryIdx !== null) {
      // Location is carried by the tag itself: no standalone entry/exit dots,
      // because an unexplained dot on a price chart is unreadable.
      nodes.push(marker(t, t.entryTime, `E${t.id}`, blue, true, 'Entry'));
      // Exit code mirrors the event guide: TP, SL, EO (short enough to stay compact).
      const exitCode = t.reason === 'TP' ? 'TP' : t.reason === 'SL' ? 'SL' : 'EO';
      nodes.push(
        marker(t, t.exitTime, `${exitCode}${t.id}`, t.reason === 'TP' ? green : t.reason === 'SL' ? red : blue, false, 'Exit', t.reason),
      );
    }

    if (context && t.signal !== undefined) {
      const shadeIdx = candleIndexAt(data, t.signal);
      const availIdx = candleIndexAt(data, t.signal + M15_MS);
      if (shadeIdx !== null) {
        nodes.push(
          <rect
            key={`shade${t.id}`}
            x={x(shadeIdx) - slot / 2}
            y={pad.t}
            width={slot}
            height={plotH}
            fill="var(--warning)"
            opacity=".07"
          />,
        );
      }
      if (availIdx !== null) {
        nodes.push(
          <g key={`avail${t.id}`}>
            <line
              x1={x(availIdx)}
              x2={x(availIdx)}
              y1={pad.t}
              y2={pad.t + plotH}
              stroke={blue}
              strokeDasharray="2 5"
              opacity=".45"
            />
            <text x={x(availIdx) + 5} y={pad.t - 5} style={{ fontSize: 9.5, fill: blue }}>
              Signal available
            </text>
          </g>,
        );
      }
    }

    return nodes;
  });

  const hoverCandle = hover !== null ? data[hover] : null;

  return (
    <div className="chart-wrap" ref={hostRef}>
      <div className="chart-tools">
        <button aria-label="Zoom in" onClick={() => setZoom((v) => Math.min(5, v + 0.5))}><Plus size={13} /></button>
        <button aria-label="Zoom out" onClick={() => setZoom((v) => Math.max(1, v - 0.5))}><Minus size={13} /></button>
        <button aria-label="Reset view" onClick={() => { setZoom(1); setPan(0); }}><RotateCcw size={13} /></button>
      </div>
      <svg
        ref={ref}
        role="img"
        aria-label={context ? 'Selected trade candle context' : 'Interactive BID candlestick chart'}
        onPointerDown={(e) => { drag.current = e.clientX; e.currentTarget.setPointerCapture(e.pointerId); }}
        onPointerUp={() => { drag.current = null; }}
        onPointerMove={(e) => {
          const r = e.currentTarget.getBoundingClientRect();
          if (!ready || slot <= 0) return;
          setHover(clamp(Math.floor(((e.clientX - r.left) - pad.l) / slot), 0, data.length - 1));
          if (drag.current !== null) {
            setPan((v) => Math.max(0, v + Math.round((drag.current! - e.clientX) / 8)));
            drag.current = e.clientX;
          }
        }}
        onPointerLeave={() => setHover(null)}
      >
        {ready && (
          <g>
            {[0, 1, 2, 3, 4].map((i) => {
              const gy = pad.t + (plotH / 4) * i;
              return (
                <g key={`grid${i}`}>
                  <line x1={pad.l} x2={pad.l + plotW} y1={gy} y2={gy} className="gridline" />
                  <text x={pad.l + plotW + 7} y={gy + 4} style={{ fontSize: 10 }}>
                    {fmt(hi - (i * (hi - lo)) / 4)}
                  </text>
                </g>
              );
            })}

            {data.map((c, i) => (
              <g key={c.t}>
                <line x1={x(i)} x2={x(i)} y1={y(c.h)} y2={y(c.l)} stroke={c.c >= c.o ? green : red} />
                <rect
                  x={x(i) - Math.max(0.6, slot * 0.3)}
                  y={y(Math.max(c.o, c.c))}
                  width={Math.max(1.4, slot * 0.6)}
                  height={Math.max(1, Math.abs(y(c.o) - y(c.c)))}
                  fill={c.c >= c.o ? green : red}
                />
                {i % labelEvery === 0 && (
                  <text x={x(i)} y={pad.t + plotH + 20} textAnchor="middle" style={{ fontSize: 10 }}>
                    {time(c.t).slice(0, 5)}
                  </text>
                )}
              </g>
            ))}

            {context && trade &&
              ([['Entry', trade.entry, blue], ['SL', trade.sl, red], ['TP', trade.tp, green]] as const).map(
                ([label, price, color]) => (
                  <g key={label}>
                    <line
                      x1={pad.l}
                      x2={pad.l + plotW}
                      y1={y(price)}
                      y2={y(price)}
                      stroke={color}
                      strokeDasharray="5 4"
                    />
                    <text x={pad.l + 5} y={y(price) - 5} style={{ fill: color, fontSize: 10 }}>
                      {`${label} ${fmt(price)}`}
                    </text>
                  </g>
                ),
              )}

            {overlays}

            {hoverCandle && hover !== null && (
              <g>
                <line
                  x1={x(hover)}
                  x2={x(hover)}
                  y1={pad.t}
                  y2={pad.t + plotH}
                  stroke="var(--muted-foreground)"
                  strokeDasharray="3 3"
                />
                <rect
                  x={pad.l + 4}
                  y={pad.t + 4}
                  width={Math.min(430, plotW - 8)}
                  height="25"
                  rx="4"
                  fill="var(--surface-elevated)"
                />
                <text x={pad.l + 12} y={pad.t + 21} style={{ fontSize: 11 }}>
                  {`${time(hoverCandle.t).slice(0, 5)}  O ${fmt(hoverCandle.o)}  H ${fmt(hoverCandle.h)}  L ${fmt(hoverCandle.l)}  C ${fmt(hoverCandle.c)}`}
                </text>
              </g>
            )}
          </g>
        )}
      </svg>
      <div className="chart-foot">
        <span><i style={{ background: green }} />BID candles</span>
        {context ? (
          <>
            <span><i style={{ background: 'var(--warning)' }} />Signal candle</span>
            <span><i style={{ background: blue }} />Entry / available</span>
          </>
        ) : (
          <>
            <span><i style={{ background: green }} />L / S = signal</span>
            <span><i style={{ background: blue }} />E = entry · SL / TP / EOD = exit</span>
          </>
        )}
        <span className="chart-hint">Scroll to zoom · drag to pan</span>
      </div>
    </div>
  );
}

export function TickChart({ trade, view, excursionAvailable = true }: { trade: Trade; view: string; excursionAvailable?: boolean }) {
  const [hover, setHover] = useState<number | null>(null);
  const { ref, width, height, ready } = useElementSize();

  const full = view === 'Full Trade';
  const exit = view === 'Exit Window';

  const arr = full
    ? tradePath(trade)
    : ticks(trade, exit ? 'exit' : 'entry', 30);

  const levels = full || exit ? [trade.entry, trade.sl, trade.tp] : [trade.entry];
  const lo = Math.min(...arr.map((a) => a.bid), ...levels) - 0.25;
  const hi = Math.max(...arr.map((a) => a.ask), ...levels) + 0.25;

  const pad = { l: 58, r: 62, t: 30, b: 36 };
  const plotW = Math.max(40, width - pad.l - pad.r);
  const plotH = Math.max(40, height - pad.t - pad.b);
  const y = (v: number) => pad.t + ((hi - v) / (hi - lo || 1)) * plotH;
  const x = (i: number) => pad.l + (i / Math.max(1, arr.length - 1)) * plotW;
  const anchor = full ? 0 : 30;

  return (
    <div className="tick-chart">
      <svg
        ref={ref}
        role="img"
        aria-label={`${trade.direction === 'LONG' ? 'Long' : 'Short'} trade ${trade.id} tick chart, ${view}`}
        onPointerMove={(e) => {
          const r = e.currentTarget.getBoundingClientRect();
          if (!ready || plotW <= 0) return;
          setHover(clamp(Math.round((((e.clientX - r.left) - pad.l) / plotW) * (arr.length - 1)), 0, arr.length - 1));
        }}
        onPointerLeave={() => setHover(null)}
      >
        {ready && (
          <g>
            {[0, 1, 2, 3].map((i) => {
              const gy = pad.t + (plotH / 3) * i;
              return (
                <g key={`tg${i}`}>
                  <line x1={pad.l} x2={pad.l + plotW} y1={gy} y2={gy} className="gridline" />
                  <text x={pad.l + plotW + 7} y={gy + 4} style={{ fontSize: 10 }}>
                    {fmt(hi - (i * (hi - lo)) / 3)}
                  </text>
                </g>
              );
            })}

            {(['bid', 'ask'] as const).map((k, i) => (
              <path
                key={k}
                d={arr.map((a, n) => `${n ? 'L' : 'M'}${x(n)} ${y(a[k])}`).join(' ')}
                fill="none"
                stroke={i ? 'var(--warning)' : blue}
                strokeWidth="1.7"
              />
            ))}

            {([['Entry', trade.entry, blue], ...(exit || full
              ? [['SL', trade.sl, red], ['TP', trade.tp, green]] as const
              : [])] as const).map(([label, price, color]) => (
              <g key={label}>
                <line
                  x1={pad.l}
                  x2={pad.l + plotW}
                  y1={y(price)}
                  y2={y(price)}
                  stroke={color}
                  strokeDasharray="4 4"
                />
                <text x={pad.l + 6} y={y(price) - 5} style={{ fill: color, fontSize: 10 }}>
                  {`${label} ${fmt(price)}`}
                </text>
              </g>
            ))}

            <line
              x1={x(anchor)}
              x2={x(anchor)}
              y1={pad.t}
              y2={pad.t + plotH}
              stroke={green}
              strokeDasharray="3 3"
            />
            <text x={x(anchor) + 5} y={pad.t - 9} style={{ fill: green, fontSize: 10 }}>
              {exit ? 'Exit' : full ? 'Entry' : 'Signal available / Entry'}
            </text>

            {full && (
              <>
                <line
                  x1={x(80)}
                  x2={x(80)}
                  y1={pad.t}
                  y2={pad.t + plotH}
                  stroke={red}
                  strokeDasharray="3 3"
                />
                <text x={x(80) - 26} y={pad.t - 9} style={{ fill: red, fontSize: 10 }}>Exit</text>
              </>
            )}

            {/* MAE / MFE extremes on the seeded replay path (demo runs only) */}
            {full && excursionAvailable && (() => {
              const ex = excursions(trade);
              const idxOf = (ms: number) =>
                Math.max(0, Math.min(arr.length - 1, Math.round(((ms - trade.entryTime) / Math.max(1, trade.exitTime - trade.entryTime)) * (arr.length - 1))));
              const long = trade.direction === 'LONG';
              const maePt = arr[idxOf(ex.maeTime)];
              const mfePt = arr[idxOf(ex.mfeTime)];
              const maeY = y(long ? maePt.bid : maePt.ask);
              const mfeY = y(long ? mfePt.bid : mfePt.ask);
              return (
                <g>
                  <line x1={x(idxOf(ex.maeTime))} x2={x(idxOf(ex.maeTime))} y1={pad.t} y2={pad.t + plotH} stroke={red} strokeDasharray="1 4" opacity=".7" />
                  <circle cx={x(idxOf(ex.maeTime))} cy={maeY} r="4" fill="none" stroke={red} strokeWidth="1.6" />
                  <text x={x(idxOf(ex.maeTime)) + 9} y={maeY + 12} style={{ fill: red, fontSize: 10 }}>MAE {fmt(ex.mae)}</text>
                  <line x1={x(idxOf(ex.mfeTime))} x2={x(idxOf(ex.mfeTime))} y1={pad.t} y2={pad.t + plotH} stroke={green} strokeDasharray="1 4" opacity=".7" />
                  <circle cx={x(idxOf(ex.mfeTime))} cy={mfeY} r="4" fill="none" stroke={green} strokeWidth="1.6" />
                  <text x={x(idxOf(ex.mfeTime)) + 9} y={mfeY - 10} style={{ fill: green, fontSize: 10 }}>MFE {fmt(ex.mfe)}</text>
                </g>
              );
            })()}

            {[0, 15, 30, 45, 60].map((n, i) => {
              const idx = Math.round((i * (arr.length - 1)) / 4);
              return (
                <text key={n} x={x(idx)} y={pad.t + plotH + 21} textAnchor="middle" style={{ fontSize: 10 }}>
                  {time(arr[idx].t).slice(0, 8)}
                </text>
              );
            })}

            {hover !== null && arr[hover] && (
              <g>
                <line
                  x1={x(hover)}
                  x2={x(hover)}
                  y1={pad.t}
                  y2={pad.t + plotH}
                  stroke="var(--muted-foreground)"
                  strokeDasharray="2 2"
                />
                <rect
                  x={clamp(x(hover) - 175, pad.l, pad.l + plotW - 350)}
                  y={pad.t + 3}
                  width="350"
                  height="24"
                  rx="3"
                  fill="var(--surface-elevated)"
                />
                <text x={clamp(x(hover) - 168, pad.l + 7, pad.l + plotW - 343)} y={pad.t + 19} style={{ fontSize: 11 }}>
                  {`${time(arr[hover].t)} BID ${fmt(arr[hover].bid)} ASK ${fmt(arr[hover].ask)}`}
                </text>
              </g>
            )}
          </g>
        )}
      </svg>
      <div className="chart-foot">
        <span><i style={{ background: blue }} />BID</span>
        <span><i style={{ background: 'var(--warning)' }} />ASK</span>
        <span className="chart-hint">
          {full ? (excursionAvailable
            ? 'Sampled replay · MAE / MFE derived from this path'
            : 'MAE / MFE not supplied by this run') : '±30 seconds · UTC'}
        </span>
      </div>
      {full && <p className="demo-note">Seeded visualization only; no execution engine runs in this prototype.</p>}
    </div>
  );
}

export function Equity({ mode }: { mode: string }) {
  const [hover, setHover] = useState<number | null>(null);
  const { ref, width, height, ready } = useElementSize();
  const state = useRun();
  const run = state.status === 'ready' ? state.run : null;

  // Compute derived data in hooks at the top (before any early returns)
  const pnl = useMemo(() => run?.equity.map((p) => p.pnl) ?? [], [run]);
  const timestamps = useMemo(() => run?.equity.map((p) => p.timestampUtc) ?? [], [run]);
  const accountReady = run?.account.accountReady ?? false;
  const balance = useMemo(
    () => (accountReady ? run!.equity.map((p) => p.balance ?? 0) : null),
    [run, accountReady]
  );

  const drawdown = useMemo(() => {
    const result: number[] = [];
    let peak = 0;
    for (const v of pnl) {
      peak = Math.max(peak, v);
      result.push(peak - v);
    }
    return result;
  }, [pnl]);

  // Loading / error state
  if (!run) {
    return (
      <div className="equity">
        <svg ref={ref} role="img" aria-label="Equity chart loading"></svg>
        <div className="equity-empty">
          <h3>Equity Chart</h3>
          <p>{state.status === 'loading' ? 'Loading reference run…' : state.status === 'error' ? state.error : state.status === 'malformed' ? state.message : 'Unknown state'}</p>
        </div>
      </div>
    );
  }

  // Balance mode without account data
  if (mode === 'Balance' && !accountReady) {
    return (
      <div className="equity">
        <svg ref={ref} role="img" aria-label="Balance chart unavailable"></svg>
        <div className="equity-empty">
          <h3>Balance — Not available</h3>
          <PendingMetric
            label="Balance"
            reason={run.metrics.accountUnavailableReasons ?? ['No account model configured.']}
            required={['Account currency', 'Initial balance', 'Account-currency PnL']}
            status="Not available"
            note="A balance chart requires a valid account model. The seeded demo produces PnL in price terms only; price PnL is never added to an assumed base balance."
          />
        </div>
      </div>
    );
  }

  const showBalance = mode === 'Balance' && balance !== null;
  const underwater = mode === 'Drawdown';

  let lo: number;
  let hi: number;
  if (underwater) {
    lo = -1;
    hi = Math.max(1, ...drawdown) + 1;
  } else if (showBalance && balance) {
    const span = Math.max(...balance) - Math.min(...balance);
    const padAmt = Math.max(6, span * 0.5);
    lo = Math.min(...balance) - padAmt;
    hi = Math.max(...balance) + padAmt;
  } else {
    lo = Math.min(0, ...pnl) - 3;
    hi = Math.max(0, ...pnl) + 3;
  }

  const pad = { l: 46, r: 14, t: 14, b: 24 };
  const plotW = Math.max(40, width - pad.l - pad.r);
  const plotH = Math.max(40, height - pad.t - pad.b);
  const last = Math.max(1, pnl.length - 1);
  const x = (i: number) => (pnl.length === 1 ? pad.l + plotW / 2 : pad.l + (i / last) * plotW);
  const y = (v: number) => pad.t + ((hi - v) / (hi - lo || 1)) * plotH;

  const primary = underwater ? drawdown : showBalance && balance ? balance : pnl;
  const path = primary.map((v, i) => `${i ? 'L' : 'M'}${x(i)} ${y(v)}`).join(' ');
  const area = `${path} L${x(last)} ${pad.t + plotH} L${x(0)} ${pad.t + plotH} Z`;
  const accent = underwater ? 'var(--warning)' : blue;

  const finalBalance = balance ? balance[balance.length - 1] : null;
  const startBalance = balance && balance.length > 1 ? balance[0] : null;
  const totalReturnPct =
    finalBalance !== null && startBalance !== null && startBalance > 0
      ? ((finalBalance - startBalance) / startBalance) * 100
      : null;

  return (
    <div className="equity">
      <svg ref={ref} role="img" aria-label={`${mode} chart`} onPointerLeave={() => setHover(null)}>
        {ready && (
          <g>
            {[0, 1, 2, 3, 4].map((i) => {
              const gy = pad.t + (plotH / 4) * i;
              return (
                <g key={`eg${i}`}>
                  <line x1={pad.l} x2={pad.l + plotW} y1={gy} y2={gy} className="gridline" />
                  <text x={4} y={gy + 4} style={{ fontSize: 10 }}>{(hi - ((hi - lo) * i) / 4).toFixed(showBalance ? 0 : 1)}</text>
                </g>
              );
            })}

            {/* zero-PnL reference line for the price-term view */}
            {!underwater && !showBalance && (
              <>
                <line x1={pad.l} x2={pad.l + plotW} y1={y(0)} y2={y(0)} stroke="var(--muted-foreground)" strokeDasharray="3 3" />
                <text x={pad.l + plotW - 2} y={y(0) - 4} textAnchor="end" style={{ fontSize: 9 }}>0</text>
              </>
            )}

            <path d={area} fill={accent} opacity=".09" />
            <path d={path} stroke={accent} strokeWidth="1.8" fill="none" />

            {primary.map((v, i) => (
              <g key={i} onPointerEnter={() => setHover(i)}>
                <rect
                  x={x(i) - Math.max(6, plotW / pnl.length / 2)}
                  y={pad.t}
                  width={Math.max(12, plotW / pnl.length)}
                  height={plotH}
                  fill="transparent"
                />
                <circle cx={x(i)} cy={y(v)} r={hover === i ? 4.5 : 2.4} fill={accent} />
                <text x={x(i)} y={pad.t + plotH + 17} textAnchor="middle" style={{ fontSize: 10 }}>
                  {i + 1}
                </text>
              </g>
            ))}

            {hover !== null && hover < primary.length && (
              <text x={pad.l} y={pad.t - 4} style={{ fontSize: 11 }}>
                {`Trade ${hover + 1} · ${formatUtcMs(Date.parse(timestamps[hover]))} · ${
                  underwater
                    ? `drawdown ${fmt(drawdown[hover])}`
                    : showBalance && balance
                      ? `balance ${fmt(balance[hover])}`
                      : `PnL ${fmt(pnl[hover])}`
                }`}
              </text>
            )}
          </g>
        )}
      </svg>
      <div className="chart-foot equity-legend">
        {underwater ? (
          <span><i style={{ background: 'var(--warning)' }} />Drawdown · price terms — not account currency</span>
        ) : showBalance ? (
          <span><i style={{ background: blue }} />Balance · account currency</span>
        ) : (
          <span><i style={{ background: blue }} />Cumulative PnL · price terms — not account currency</span>
        )}
        <span className="chart-hint">Trade #</span>
      </div>
      <dl className="equity-summary">
        <div><dt>Final PnL</dt><dd>{fmt(pnl[pnl.length - 1] ?? 0)} <span className="meta">price terms</span></dd></div>
        <div><dt>Max Drawdown</dt><dd>{fmt(drawdown.length ? Math.max(...drawdown) : 0)} <span className="meta">price terms</span></dd></div>
        <div>
          <dt>Balance</dt>
          <dd>{finalBalance !== null ? fmt(finalBalance) : 'Not available'}</dd>
        </div>
        <div>
          <dt>Total Return</dt>
          <dd>{totalReturnPct !== null ? <span className={totalReturnPct < 0 ? 'bad-text' : 'good-text'}>{totalReturnPct.toFixed(2)}%</span> : 'Not available'}</dd>
        </div>
      </dl>
    </div>
  );
}